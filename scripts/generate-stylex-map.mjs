/**
 * Generates app/Support/stylex-map.php from resources/js/stylex.js.
 *
 * StyleX compiles `stylex.create({...})` into deterministic content-hash
 * class names. This script runs the same babel transform the Vite unplugin
 * uses, then dumps a PHP map of `styleKey => "class1 class2 ..."` so Blade
 * templates can reference semantic keys via the `@stylex` directive.
 *
 * Run with: node scripts/generate-stylex-map.mjs
 */
import { transformSync } from '@babel/core';
import plugin from '@stylexjs/babel-plugin';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const sourceFile = path.join(root, 'resources', 'js', 'stylex.js');
const outFile = path.join(root, 'app', 'Support', 'stylex-map.php');

const source = fs.readFileSync(sourceFile, 'utf8');

const result = transformSync(source, {
    babelrc: false,
    configFile: false,
    plugins: [
        [
            plugin,
            {
                runtimeInjection: false,
                dev: false,
                importSources: ['@stylexjs/stylex'],
            },
        ],
    ],
});

// The transform leaves `import * as stylex from '@stylexjs/stylex';` plus
// `export const styles = { key: { kHash: "xHash", $$css: true } };`.
// Strip the import, rewrite the export, evaluate to a plain object.
const code = result.code
    .replace(/import\s+[^;]+;/g, '')
    .replace('export const styles =', 'const styles =');

const styles = new Function(`${code}; return styles;`)();

const map = {};
for (const [key, style] of Object.entries(styles)) {
    if (!style || style.$$css !== true) continue;
    const classes = Object.entries(style)
        .filter(([k]) => k !== '$$css' && typeof style[k] === 'string')
        .map(([, v]) => v)
        .join(' ');
    map[key] = classes;
}

const lines = ['<?php', '', '// Generated by scripts/generate-stylex-map.mjs — do not edit by hand.', '// Run `npm run stylex:map` after changing resources/js/stylex.js.', '', 'return [']; 
const quote = (value) => `'${value}'`;
for (const [key, classes] of Object.entries(map)) {
    lines.push(`    ${quote(key)} => ${quote(classes)},`);
}
lines.push('];', '');

const php = lines.join('\n');

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, php, 'utf8');

console.log(`Wrote ${Object.keys(map).length} style keys to ${path.relative(root, outFile)}`);